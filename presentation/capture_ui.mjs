import { chromium } from "../frontend/node_modules/playwright-core/index.mjs";
const OUT = "D:/bia hackathon/presentation/presentation_assets";
const b = await chromium.launch({ channel: "msedge", headless: true });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light", reducedMotion: "reduce" });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
const nav = async (name) => { await p.getByRole("navigation", { name: "Main" }).getByRole("link", { name }).click(); await p.waitForTimeout(1500); };
await p.goto("http://127.0.0.1:8000/"); await p.waitForSelector("text=Customer referral"); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/ui_overview.png` });
await nav("Customer prediction");
await p.getByRole("button", { name: /Load example/ }).click();
await p.getByRole("button", { name: /Predict outcomes/ }).click();
await p.waitForSelector("[data-testid=cost-value]"); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/ui_predict.png` });
await nav("Roofing comparison"); await p.waitForSelector("text=Recommended"); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/ui_compare.png` });
await nav("Model performance"); await p.waitForSelector("text=Candidate models"); await p.waitForTimeout(1200);
await p.getByRole("tab", { name: /Referral/ }).click(); await p.waitForSelector("text=Cut-off trade-off"); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/ui_performance.png` });
await nav("Proposal"); await p.waitForSelector("text=What the proposal will say"); await p.waitForTimeout(1000);
await p.screenshot({ path: `${OUT}/ui_proposal.png` });
await nav("AI assistant"); await p.waitForSelector("text=Provider:");
await p.locator("#chat").fill("Urban house, flat concrete roof, 1500 sq ft, 2 ACs, around 140 kWh a month. Which option do you recommend?");
await p.getByRole("button", { name: /Send/ }).click();
await p.waitForSelector("text=Figures come from the prediction service", { timeout: 90000 }); await p.waitForTimeout(1200);
await p.evaluate(() => { const l = document.querySelector("[role=log]"); if (l) l.scrollTop = 0; });
await p.screenshot({ path: `${OUT}/ui_assistant.png` });
console.log("screenshots done; page errors:", errs.length); await b.close();
